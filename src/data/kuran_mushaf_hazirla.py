# ── Vakıf veritabanı — (sure, ayet, kelime_indis_0): işaret
# Tam veri tanzil.net XML'inden gelecek (vakif_ekle.py)
# Şimdilik Fatiha tam, diğerleri kısmi örnek
VAKIF_DB = {
    (1,1,3):"ط",(1,2,3):"ط",(1,3,1):"ج",
    (1,4,2):"ط",(1,5,3):"ط",(1,6,3):"ج",
    (2,2,2):"ط",(2,5,2):"ط",(2,7,4):"م",
}

def sayfa_bul(sure_no, ayet_no, harita):
    sayfa = 1
    for s_no, su_no, a_no in harita:
        if su_no > sure_no or (su_no == sure_no and a_no > ayet_no):
            break
        sayfa = s_no
    return sayfa

def main():
    base = Path(__file__).parent

    # kuran.json'u bul — data/ veya public/ içinde olabilir
    kuran_path = None
    for aday in [base / "kuran.json", base.parent.parent / "public" / "kuran.json"]:
        if aday.exists():
            kuran_path = aday
            break

    if not kuran_path:
        print("HATA: kuran.json bulunamadı")
        print("  Aranan: src/data/kuran.json veya public/kuran.json")
        return

    with open(kuran_path, encoding="utf-8") as f:
        sureler = json.load(f)

    print(f"✓ kuran.json yüklendi — {len(sureler)} sure ({kuran_path})")

    # ── sayfa-harita.json üret (tekrarsız, gerçek sayfa başları)
    goruldu = set()
    sayfa_haritasi = []
    for s_no, su_no, a_no in SAYFA_HARITASI_RAW:
        anahtar = (su_no, a_no)
        if anahtar not in goruldu:
            sayfa_haritasi.append({"sayfa": s_no, "sure": su_no, "ayet": a_no})
            goruldu.add(anahtar)

    sayfa_harita_path = base / "sayfa-harita.json"
    with open(sayfa_harita_path, "w", encoding="utf-8") as f:
        json.dump(sayfa_haritasi, f, ensure_ascii=False, indent=2)
    print(f"✓ sayfa-harita.json — {len(sayfa_haritasi)} benzersiz sayfa başı")

    # ── kuran-mushaf.json üret
    mushaf = []
    toplam_kelime = 0

    for sure in sureler:
        sure_no = sure["id"]
        ayetler_mushaf = []

        for ayet in sure["ayetler"]:
            ayet_no = ayet["no"]
            arapca  = ayet["arapca"].strip()
            kelime_listesi = arapca.split()
            kelimeler = []

            for ki, ham in enumerate(kelime_listesi):
                vakif = VAKIF_DB.get((sure_no, ayet_no, ki), None)
                # Secde işareti son kelimede gösterilir
                secde = "سَجْدَة" if (
                    (sure_no, ayet_no) in SECDE_AYETLERI and
                    ki == len(kelime_listesi) - 1
                ) else None

                kelimeler.append({
                    "id": f"{sure_no}:{ayet_no}:{ki+1}",
                    "arabic": ham,
                    "vakif": vakif,
                    "secde": secde,
                })

            toplam_kelime += len(kelimeler)
            sayfa = sayfa_bul(sure_no, ayet_no, SAYFA_HARITASI_RAW)

            ayetler_mushaf.append({
                "no":       ayet_no,
                "sayfa":    sayfa,
                "kelimeler": kelimeler,
            })

        mushaf.append({
            "id":          sure_no,
            "isim":        sure["isim"],
            "isimArapca":  sure.get("isimArapca", ""),
            "anlam":       sure.get("anlam", ""),
            "yer":         sure.get("yer", ""),
            "ayetSayisi":  sure["ayetSayisi"],
            "ayetler":     ayetler_mushaf,
        })

    mushaf_path = base / "kuran-mushaf.json"
    with open(mushaf_path, "w", encoding="utf-8") as f:
        json.dump(mushaf, f, ensure_ascii=False, separators=(",", ":"))

    boyut_mb = mushaf_path.stat().st_size / 1024 / 1024
    print(f"✓ kuran-mushaf.json — {boyut_mb:.1f} MB, {toplam_kelime:,} kelime")
    print()
    print("Sonraki adım:")
    print("  Vakıf verisini eklemek için tanzil.net XML'ini indir")
    print("  ve vakif_ekle.py scriptini çalıştır (bir sonraki adımda yazılacak)")

if __name__ == "__main__":
    main()
